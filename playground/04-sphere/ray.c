t_ray	camera_ray(int x, int y)
{
	t_ray	r;
	double	u;
	double	v;
	double	aspect;
	double	sx;
	double	sy;

	// 우리는 창(창문)의 최종 위치를 구해야한다
	// 그러나, 픽셀 번호는 0 ~ 799 같은 정수
	// 따라서 화면에서 비율에 따른 값으로 표현하기 위해서 0~1사이의 값으로 표현함
	u = x / (double)(WIN_WIDTH - 1);
	v = y / (double)(WIN_HEIGHT - 1);

	// 범위를 -1 ~ +1 사이로 변경하는 것
	// 중앙 좌표가 (0, 0)
	aspect = WIN_WIDTH / (double)WIN_HEIGHT;  // 정사각형 -> 화면 크기로 변경
	sx = (2 * u - 1) * aspect;
	// double sx = 2 * u - 1; // 두배 늘리고 -1해서 중앙을 맞춤. 예: 0.5 -> 0, 0.2->-0.6
	sy = 1 - 2 * v; // 동일하나, *-1함. 에: 0.2 -> 0.6 why? 화면은 맨 위가 0이라서 아래로 갈수록 작아짐. 실제 화면과 일치시키기 위한 식 

	// 눈은 원점, 화면은 -1
	r.origin = (t_vec3){0.0, 0.0, 0.0};
	r.direction = vec3_normalize((t_vec3){sx, sy, -1});

	return (r);
}
