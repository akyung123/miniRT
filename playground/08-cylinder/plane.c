#include "miniRT.h"

/*
평면과 광선이 만나는 t 구하기

1) 평면: 점 P0를 지나고 법선이 n인 평면 위의 점 P는
         'P0에서 P로 가는 화살표'가 평면 안에 누워 있으니 n과 수직
         n·(P - P0) = 0

              n ↑
                │
   ─────────P0──●──────P────  평면
                └──────┘
                 P - P0 (n과 수직 → 내적 0)

2) 광선 대입: P = A + t·d
         n·(A + t·d - P0) = 0
         n·(A - P0) + t(n·d) = 0

3) t에 대해 1차식이라 바로 풀린다 (판별식도, 근 두 개도 없다)
         t = n·(P0 - A) / (n·d)

4) 분모 n·d 의 뜻
         n·d = cos(법선과 광선 사이 각)
         0에 가까우면 광선이 평면과 나란히 달린다 → 영원히 안 만남
         부동소수점은 정확히 0이 거의 안 나오니 == 0 대신 fabs < 1e-6

평면은 무한하다. P0를 평면 안에서 어디로 옮기든 같은 평면이고 t도 같다
(n·(P0 - A) 에서 평면 안쪽 방향 성분은 n과 수직이라 전부 0이 되니까)

맞으면 t (양수), 안 맞으면 -1.0
*/
double	hit_plane(t_ray r, t_vec3 point, t_vec3 normal,
			double t_min, double t_max)
{
	double	denom;
	double	t;

	denom = vec3_dot(normal, r.direction);
	// 평행: 0으로 나누면 inf/nan이 화면 절반을 덮는다
	if (fabs(denom) < 1e-6)
		return (-1.0);
	t = vec3_dot(normal, vec3_sub(point, r.origin)) / denom;
	// t < t_min : 평면이 카메라 뒤 (평면은 무한해서 이걸 빼먹으면 화면 전체가 덮인다)
	// t > t_max : 이미 더 가까운 물체가 있다 / 광원보다 멀다
	// 부호는 따로 신경 쓸 필요 없다: 법선이 어느 쪽을 보든 분자/분모 부호가 같이 뒤집힌다
	if (t <= t_min || t >= t_max)
		return (-1.0);
	return (t);
}
